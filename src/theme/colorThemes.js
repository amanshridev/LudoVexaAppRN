export function buildSemanticTheme(themeId = 'slate') {
  const found = THEME_LIST.find((t) => t.id === themeId) || THEME_LIST.find((t) => t.id === 'slate') || THEME_LIST[0];

  return {
    id: found.id,
    name: found.name,
    colors: {
      primary: found.primary,
      primaryLight: found.primaryLight,
      primaryDark: found.primaryDark,
      onPrimary: found.onPrimary || '#FFFFFF',
      background: found.background,
      surface: found.surface,
      surfaceCard: found.card,
      surfaceElevated: found.elevated,
      text: found.text || '#FFFFFF',
      secondaryText: found.secondaryText || '#CBD5E1',
      mutedText: found.mutedText || '#94A3B8',
      border: found.border,
      borderActive: found.primary,
      success: '#10B981',
      warning: '#FACC15',
      error: '#EF4444',
    },
  };
}